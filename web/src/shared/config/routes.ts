/**
 * 경로 문자열의 원본입니다.
 *
 * 프로그래밍 방식 이동과 템플릿 링크가 이 상수를 경유합니다. 경로가 흩어지면
 * URL 구조를 바꿀 때 문자열 검색에 의존하게 되며 오타는 런타임에만 드러납니다.
 * 규칙은 docs/architecture/references/08-routing.md 2.1절입니다.
 *
 * 경로 세그먼트는 ASCII 로만 작성합니다. 한글 경로는 정적 생성까지는 통과하지만
 * 서빙 단계에서 404 가 되며, 빌드가 성공하므로 요청해 보기 전에는 드러나지 않습니다.
 */
export const ROUTES = {
  home: () => '/',

  /**
   * 관점별 목록입니다. 관점이 경로에 있는 이유는 그것이 이동이기 때문입니다. 관점을 바꾸면
   * 목록의 내용이 통째로 바뀌므로 곁에 남을 것이 없습니다. 08-routing.md 3절.
   *
   * 인자를 관점 타입이 아니라 문자열로 받습니다. `shared` 는 가장 아래 계층이라 엔티티의
   * 타입을 참조할 수 없습니다. 좁히는 것은 화면이 `toTaskView` 로 합니다.
   * 02-package-structure.md 5.1절.
   */
  taskList: (view = 'all') => `/tasks/${view}`,
} as const;

/**
 * 상세 패널이 여는 항목의 쿼리 파라미터입니다.
 *
 * 경로가 아니라 쿼리 파라미터인 이유는 목록을 곁에 두어야 하기 때문입니다. 경로가 바뀌면
 * 라우터가 목록을 언마운트하고 전환 베일이 목록을 덮습니다. 기각한 대안은 상세를
 * `/tasks/:id` 별도 페이지로 두는 것이었고, 위 사유로 쿼리 파라미터로 옮겼습니다.
 *
 * 파라미터 이름을 이 자리에 모아 두면 여는 쪽과 닫는 쪽이 같은 문자열을 각자 적지 않습니다.
 */
export const TASK_PANEL = {
  /** 화면이 읽는 이름입니다. 라우트 입력 바인딩의 속성명과 같아야 합니다. */
  param: 'task',
  open: (id: string) => ({ task: id }),
  close: () => ({ task: null }),
} as const;
