package dev.goraebap.devkit.auth.application.shared;

import java.util.Locale;

/**
 * HMAC의 용도. 같은 키로 계산하더라도 <b>용도가 다르면 다른 다이제스트가 나오게</b> 한다
 * (보안 검토 F5).
 *
 * <p><b>왜 필요한가.</b> 세션 토큰 해시·OTP 코드 해시·소셜 표 서명이 모두 같은 앱 시크릿을
 * 키로 쓴다. 용도 라벨이 없으면 이들은 <b>같은 함수의 출력</b>이라, 한 용도에서 얻은 값이 다른
 * 용도에서 그대로 통하는 길이 열릴 수 있다. 표 서명은 이 시스템에서 <b>유일하게 클라이언트에게
 * 노출되는 HMAC 출력</b>이라 특히 그렇다.
 *
 * <p>지금 코드에서 실제 악용 경로는 찾지 못했다 — 세션 조회는 역상을 요구하고, OTP는 6자리라
 * 형식이 다르며, 표 페이로드는 서버가 조립한다. <b>그러나 이 저장소는 키트다.</b> 파생 프로젝트가
 * 네 번째 HMAC 용도를 추가하는 순간 그 안전은 우연이 된다. 용도를 타입으로 강제하면 그 우연에
 * 기대지 않아도 된다.
 *
 * <p><b>지금 넣는 이유.</b> 라벨을 붙이면 저장된 다이제스트의 값이 바뀐다. 배포 전인 지금은
 * 무비용이지만, 운영 데이터가 생긴 뒤에는 <b>살아 있는 세션과 대기 레코드를 전부 무효화하는
 * 마이그레이션</b>이 된다.
 */
public enum HmacPurpose {
    /** 세션 토큰 → {@code sessions.token_hash} */
    SESSION,

    /** 이메일 확인 코드 → {@code verifications.code_hash} */
    OTP,

    /** 소셜 로그인 중간 표의 서명. 이 값만 클라이언트에게 나간다 */
    SOCIAL_TICKET;

    /** 해시 입력 앞에 붙는 라벨. 값을 바꾸면 저장된 다이제스트가 전부 어긋난다. */
    public String label() {
        return name().toLowerCase(Locale.ROOT);
    }
}
